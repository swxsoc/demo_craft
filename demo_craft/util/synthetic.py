"""
Generate the synthetic level 0 files that stand in for craft telemetry.

The demo mission has no real instrument, so its level 0 product is a small,
deterministic CSV file with a ``time`` column (ISOT strings, one row per
second) and an integer ``counts`` column that traces one period of a sine
wave. The bundled test file in ``demo_craft/data/test`` is produced by
:func:`write_l0_file` and can be regenerated byte for byte with::

    python -m demo_craft.util.synthetic demo_craft/data/test
"""

import math
from datetime import UTC, datetime, timedelta
from pathlib import Path

from demo_craft.util.filename import INSTRUMENT_NAME, create_science_filename

__all__ = ["DEFAULT_TIME", "DEFAULT_VERSION", "l0_rows", "write_l0_file"]

#: Start time of the bundled test file.
DEFAULT_TIME = datetime(2026, 1, 1, 0, 0, 0, tzinfo=UTC)
#: Version of the bundled test file.
DEFAULT_VERSION = "0.0.1"
#: Mean count level of the synthetic signal.
BASELINE_COUNTS = 1000
#: Peak deviation from the baseline.
AMPLITUDE_COUNTS = 100


def l0_rows(start: datetime = DEFAULT_TIME, n_samples: int = 60) -> list:
    """
    Return the rows of a synthetic level 0 file.

    Parameters
    ----------
    start : `~datetime.datetime`
        Time of the first sample.
    n_samples : `int`
        Number of one-second samples; the sine wave completes one period.

    Returns
    -------
    rows : `list` of (`str`, `int`)
        ``(isot_time, counts)`` pairs.
    """
    rows = []
    for i in range(n_samples):
        sample_time = start + timedelta(seconds=i)
        counts = BASELINE_COUNTS + round(
            AMPLITUDE_COUNTS * math.sin(2 * math.pi * i / n_samples)
        )
        rows.append((sample_time.strftime("%Y-%m-%dT%H:%M:%S.000"), counts))
    return rows


def write_l0_file(
    directory,
    time: datetime = DEFAULT_TIME,
    version: str = DEFAULT_VERSION,
    n_samples: int = 60,
) -> Path:
    """
    Write a synthetic level 0 file into ``directory`` and return its path.

    Parameters
    ----------
    directory : `str` or `~pathlib.Path`
        Directory to write into; it is created if missing.
    time : `~datetime.datetime`
        Time of the first sample, which also names the file.
    version : `str`
        File version, ``X.Y.Z``.
    n_samples : `int`
        Number of one-second samples.

    Returns
    -------
    path : `~pathlib.Path`
        The file written, named by `~demo_craft.util.filename.create_science_filename`.

    Examples
    --------
    >>> import tempfile
    >>> from demo_craft.util.synthetic import write_l0_file
    >>> with tempfile.TemporaryDirectory() as tmp:
    ...     write_l0_file(tmp).name
    'demo_craft_l0_20260101T000000_v0.0.1.csv'
    """
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    path = directory / create_science_filename(
        instrument=INSTRUMENT_NAME, time=time, level="l0", version=version
    )
    lines = ["time,counts"] + [
        f"{sample_time},{counts}" for sample_time, counts in l0_rows(time, n_samples)
    ]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


if __name__ == "__main__":  # pragma: no cover
    import sys

    target = sys.argv[1] if len(sys.argv) > 1 else "."
    print(write_l0_file(target))
